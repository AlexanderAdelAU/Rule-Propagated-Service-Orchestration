package org.btsn.deployment;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import org.json.simple.JSONObject;

/**
 * What every host node runs besides its places, derived from the node's name so that adding a node to
 * the infrastructure (P7, P8, ...) is all it takes to get one.
 *
 * Node Pn runs Pn_InitializationService (purgeAndInitialize, base port 4300+n-1) and Pn_CollectorService
 * (collectAllData, base port 4100+n-1) on its own channel. A run initialises and later collects each host it
 * uses; the administrative token of node Pn is 999000000 + n*10000 in both phases, and Monitor's
 * initialisation token is 999000000. The initialiser and collector processes for a run's hosts are generated
 * too: common/Initializers/Hosts_Initialization and common/Collectors/Hosts_Collector.
 *
 * Arguments: processes common-folder P1,P2,...   writes the two processes for those hosts (or for run.pN properties)
 */
public final class HostAdministration {
    /** Hosts are P1 to P99: their administrative ports (4100-4198, 4300-4398) and tokens are numbered by node. */
    public static final int MAX_NODE = 99;
    public static final int COLLECTOR_BASE_PORT = 4100;
    public static final int INITIALISATION_BASE_PORT = 4300;
    public static final int ADMIN_SEQUENCE_BASE = 999000000;
    public static final String RULES_FILE = "RuleBase/Generated/HostAdministration.ruleml.xml";
    /** Hand-written lists of P1-P6's administrative services that the generated file replaces. */
    static final List<String> LEGACY_RULE_FILES = Arrays.asList(
        "RuleBase/PetriNet/ListofPetriNetInitializationServices.ruleml.xml",
        "RuleBase/PetriNet/ListofPetrinetCollectorServices.ruleml.xml");
    public static final String INITIALISER = "common/Initializers/Hosts_Initialization";
    public static final String COLLECTOR = "common/Collectors/Hosts_Collector";

    private HostAdministration() { }

    /** True for a host node name: P1 ... P99. */
    public static boolean isHost(String node) {
        return node != null && node.matches("P[1-9]\\d?");
    }

    /** P7 -> 7. */
    public static int number(String node) {
        require(isHost(node), "A host node is named P1 ... P" + MAX_NODE + ": " + node);
        return Integer.parseInt(node.substring(1));
    }

    /** The administrative token of a host in the initialisation and collection phases. */
    public static int sequence(String node) {
        return ADMIN_SEQUENCE_BASE + number(node) * 10000;
    }

    /** Monitor's initialisation token. */
    public static int monitorSequence() {
        return ADMIN_SEQUENCE_BASE;
    }

    /** activeService facts for the administrative services of every host node the infrastructure defines. */
    public static String rules(DeploymentConfiguration config) {
        StringBuilder out = new StringBuilder("<!-- Generated from the infrastructure's nodes: each host node Pn initialises its database\n"
            + "     (Pn_InitializationService, base port 4300+n-1) and reports to Monitor (Pn_CollectorService, base port 4100+n-1).\n"
            + "     Regenerated by GenerateDeploymentRules; do not edit. -->\n");
        for (Object item : DeploymentConfiguration.array(config.infrastructure, "nodes")) {
            JSONObject node = (JSONObject)item;
            String name = DeploymentConfiguration.text(node, "node");
            if (!name.matches("P\\d+")) continue;
            int n = number(name);
            String channel = DeploymentConfiguration.text(node, "channel");
            for (Object value : DeploymentConfiguration.array(node, "basePorts")) {
                int port = ((Number)value).intValue();
                require(!reserved(port), name + " uses base port " + port + ", which hosts keep for their administrative services ("
                    + COLLECTOR_BASE_PORT + "-" + (COLLECTOR_BASE_PORT + MAX_NODE - 1) + " and "
                    + INITIALISATION_BASE_PORT + "-" + (INITIALISATION_BASE_PORT + MAX_NODE - 1) + "); choose another port");
            }
            atom(out, name + "_InitializationService", "purgeAndInitialize", channel, INITIALISATION_BASE_PORT + n - 1);
            atom(out, name + "_CollectorService", "collectAllData", channel, COLLECTOR_BASE_PORT + n - 1);
        }
        return out.toString();
    }

    static boolean reserved(int port) {
        return (port >= COLLECTOR_BASE_PORT && port < COLLECTOR_BASE_PORT + MAX_NODE)
            || (port >= INITIALISATION_BASE_PORT && port < INITIALISATION_BASE_PORT + MAX_NODE);
    }

    private static void atom(StringBuilder out, String service, String operation, String channel, int port) {
        out.append("<Atom><Rel>activeService</Rel><Ind>").append(service).append("</Ind><Ind>").append(operation)
           .append("</Ind><Ind>").append(channel).append("</Ind><Ind>").append(port).append("</Ind></Atom>\n");
    }

    /** The canonical binding of a host's administrative service: one token in, the token out. */
    static String binding(String service, String operation) {
        return "<!-- Canonical Binding for " + service + " -->\n"
            + "<!-- Generated for the host node by HostAdministration - DO NOT EDIT -->\n"
            + "<!-- Input count: 1 -->\n"
            + "<!-- Return attribute from topology: token -->\n\n"
            + "<Atom>\n\t<Rel>localDefined</Rel>\n\t<Ind>" + service + "</Ind>\n</Atom>\n"
            + "<Atom>\n\t<Rel>canonicalBinding</Rel>\n\t<Ind>" + operation + "</Ind>\n\t<Ind>token</Ind>\n\t<Ind>token</Ind>\n</Atom>\n";
    }

    /**
     * Writes the generated rules file and makes the profile list it among its direct service rules, in place
     * of the hand-written P1-P6 lists; writes each host's administrative bindings (ServiceAttributeBindings/P7/...).
     * Returns the number of host nodes covered.
     */
    @SuppressWarnings("unchecked")
    static int write(Path common, DeploymentConfiguration config) throws Exception {
        String rules = rules(config);
        Path file = common.resolve(RULES_FILE);
        Files.createDirectories(file.getParent());
        Files.writeString(file, rules);
        for (Object item : DeploymentConfiguration.array(config.infrastructure, "nodes")) {
            String node = DeploymentConfiguration.text((JSONObject)item, "node");
            if (!isHost(node)) continue;
            Path folder = common.resolve("ServiceAttributeBindings").resolve(node);
            Files.createDirectories(folder);
            Files.writeString(folder.resolve(node + "_InitializationService-CanonicalBindings.ruleml.xml"),
                binding(node + "_InitializationService", "purgeAndInitialize"));
            Files.writeString(folder.resolve(node + "_CollectorService-CanonicalBindings.ruleml.xml"),
                binding(node + "_CollectorService", "collectAllData"));
            // A deployment that found no binding left a placeholder beside the folders; this binding replaces it.
            for (String service : new String[] {node + "_InitializationService", node + "_CollectorService"})
                Files.deleteIfExists(common.resolve("ServiceAttributeBindings").resolve(service + "-CanonicalBindings.ruleml.xml"));
        }
        for (String legacy : LEGACY_RULE_FILES) Files.deleteIfExists(common.resolve(legacy));
        Path profileFile = common.resolve("BusinessServiceDefinitions/Deployment.json");
        JSONObject profile = DeploymentConfiguration.read(profileFile);
        Set<String> direct = new LinkedHashSet<>();
        if (profile.get("directServiceRules") instanceof org.json.simple.JSONArray)
            for (Object name : (org.json.simple.JSONArray)profile.get("directServiceRules")) direct.add(name.toString());
        boolean changed = direct.removeAll(LEGACY_RULE_FILES);
        changed |= direct.add(RULES_FILE);
        if (changed) {
            org.json.simple.JSONArray list = new org.json.simple.JSONArray();
            list.addAll(direct);
            profile.put("directServiceRules", list);
            Files.writeString(profileFile, profile.toJSONString());
        }
        return rules.split("<Ind>purgeAndInitialize</Ind>", -1).length - 1;
    }

    /** The hosts in a comma-separated list (P1,P3,P7), in order, each once. */
    public static List<String> hosts(String list) {
        Set<String> hosts = new LinkedHashSet<>();
        for (String part : list.split("[,\\s]+")) {
            if (part.isEmpty()) continue;
            String node = part.toUpperCase(Locale.ROOT);
            number(node);
            hosts.add(node);
        }
        require(!hosts.isEmpty(), "No hosts listed");
        return new ArrayList<>(hosts);
    }

    /** The initialiser (purgeAndInitialize on each host and Monitor) or collector (each host reports to Monitor). */
    public static String process(List<String> nodes, boolean initialiser) {
        List<String> columns = new ArrayList<>(nodes);
        columns.add("Monitor");
        String generator = initialiser ? "INTIALISATION_GENERATOR" : "COLLECTION_GENERATOR";
        List<String> elements = new ArrayList<>(), arrows = new ArrayList<>();
        int generatorX = 110 + (columns.size() - 1) * 40;
        elements.add(element(generator, "EVENT_GENERATOR", generatorX, 40, 24, 60,
            "      \"rotation\": 90.0,\n      \"generator_rate\": \"1000\",\n      \"token_version\": \"v001\""));
        for (int i = 0; i < columns.size(); i++) {
            String column = columns.get(i);
            boolean monitor = "Monitor".equals(column);
            int x = 110 + i * 80;
            elements.add(element("T_in_" + column, "TRANSITION", x, 150, 20, 60,
                "      \"rotation\": 90.0,\n      \"node_type\": \"EdgeNode\",\n      \"node_value\": \"EDGE_NODE\",\n      \"transition_type\": \"T_in\",\n      \"buffer\": \"10\""));
            String service = initialiser ? (monitor ? "Monitor_InitializationService" : column + "_InitializationService")
                                         : (monitor ? "MonitorService" : column + "_CollectorService");
            String operation = initialiser ? "purgeAndInitialize" : monitor ? "writeCollectorData" : "collectAllData";
            elements.add(element(column, "PLACE", x - 15, 255, 50, 50,
                "      \"service\": \"" + service + "\",\n      \"operations\": [\n        {\n          \"name\": \"" + operation + "\"\n        }\n      ]"));
            boolean terminates = initialiser || monitor;
            elements.add(element("T_out_" + column, "TRANSITION", x, 360, 20, 60,
                "      \"rotation\": 90.0,\n      \"node_type\": \"" + (terminates ? "TerminateNode" : "EdgeNode") + "\",\n      \"node_value\": \""
                + (terminates ? "TERMINATE_NODE" : "EDGE_NODE") + "\",\n      \"transition_type\": \"T_out\""));
            arrows.add(arrow("T_in_" + column, column));
            arrows.add(arrow(column, "T_out_" + column));
            if (initialiser || !monitor) arrows.add(arrow(generator, "T_in_" + column));
            if (!initialiser && !monitor) arrows.add(arrow("T_out_" + column, "T_in_Monitor"));
        }
        return "{\n  \"processType\": \"PetriNet\",\n  \"elements\": [\n" + String.join(",\n", elements) + "\n  ],\n  \"arrows\": [\n"
            + String.join(",\n", arrows) + "\n  ],\n  \"textElements\": [\n    {\n      \"x\": 110,\n      \"y\": 20,\n      \"text\": \""
            + (initialiser ? "Initialise " : "Collect from ") + String.join(", ", nodes) + " (generated for this run)"
            + "\",\n      \"fontSize\": 12,\n      \"fontStyle\": 0,\n      \"color\": -16777216\n    }\n  ]\n}\n";
    }

    private static String element(String id, String type, int x, int y, int w, int h, String extra) {
        return "    {\n      \"id\": \"" + id + "\",\n      \"type\": \"" + type + "\",\n      \"x\": " + x + ",\n      \"y\": " + y
            + ",\n      \"width\": " + w + ",\n      \"height\": " + h + ",\n      \"label\": \"" + id + "\",\n" + extra + "\n    }";
    }

    private static String arrow(String source, String target) {
        return "    {\n      \"source\": \"" + source + "\",\n      \"target\": \"" + target
            + "\",\n      \"label\": \"\",\n      \"guardCondition\": \"\",\n      \"decision_value\": \"\",\n      \"endpoint\": \"\"\n    }";
    }

    public static void main(String[] args) throws Exception {
        require(args.length == 3 && "processes".equals(args[0]), "Expected: processes common-folder P1,P2,...");
        Path common = Path.of(args[1]);
        List<String> hosts = HostLaunch.listed(args[2], System.getProperties());
        Path folder = common.resolve("ProcessDefinitionFolder");
        Files.createDirectories(folder.resolve(INITIALISER).getParent());
        Files.createDirectories(folder.resolve(COLLECTOR).getParent());
        Files.writeString(folder.resolve(INITIALISER + ".json"), process(hosts, true));
        Files.writeString(folder.resolve(COLLECTOR + ".json"), process(hosts, false));
        System.out.println("Administrative processes for " + String.join(", ", hosts) + ": " + INITIALISER + ", " + COLLECTOR);
    }

    private static void require(boolean condition, String message) {
        if (!condition) throw new IllegalArgumentException(message);
    }
}
